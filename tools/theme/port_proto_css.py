#!/usr/bin/env python3
"""Port the prototype stylesheet (08-prototype/customer/_shared/proto.css) into
the Mendix theme as theme/web/_gitpizza-proto.scss.

* Tokens (:root) and global rules (*, html, scrollbars, keyframes) stay global.
* Every component rule is scoped under `.gp-app` (the layout root), so it wins
  over Atlas at equal specificity without !important.
* `body` rules move to the layout root; prototype-only controls are dropped.

Usage: python3 tools/theme/port_proto_css.py <proto.css> <out.scss>
"""
import re, sys

src = None
if __name__ == "__main__":
  src = open(sys.argv[1], encoding='utf-8').read()
if src is not None:
  src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

def blocks(text):
    """Yield (prelude, body) for top-level blocks."""
    i, n = 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0:
            break
        prelude = text[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            if text[k] == '{': depth += 1
            elif text[k] == '}': depth -= 1
            k += 1
        yield prelude, text[j + 1:k - 1]
        i = k

GLOBAL = {':root', '*', 'html', '*:hover', '::-webkit-scrollbar', '::-webkit-scrollbar-track, ::-webkit-scrollbar-corner',
          '::-webkit-scrollbar-thumb', '::-webkit-scrollbar-thumb:hover', ':focus-visible', 'img', 'a', 'a:hover',
          'button, input, select, textarea'}
DROP = ('.proto-fab', '.proto-panel')

def scope_sel(sel):
    sel = sel.strip()
    if sel.startswith('body.'):
        return '.gp-app.' + sel[5:]
    if sel == 'body':
        return '.gp-app'
    if sel.startswith('body '):
        return '.gp-app ' + sel[5:]
    return '.gp-app ' + sel

def convert(text, indent=''):
    out = []
    for prelude, body in blocks(text):
        if prelude.startswith('@keyframes') or prelude.startswith('@font-face'):
            out.append(f'{indent}{prelude} {{{body}}}')
        elif prelude.startswith('@media'):
            inner = convert(body, indent + '  ')
            if inner.strip():
                out.append(f'{indent}{prelude} {{\n{inner}\n{indent}}}')
        else:
            sels = [s for s in prelude.split(',') if s.strip()]
            if any(s.strip().startswith(DROP) for s in sels):
                continue
            if prelude in GLOBAL:
                if prelude in ('img', 'a', 'a:hover', 'button, input, select, textarea'):
                    new = ', '.join(scope_sel(s) for s in sels)
                else:
                    new = prelude
            else:
                new = ', '.join(scope_sel(s) for s in sels)
            out.append(f'{indent}{new} {{{body.strip()} }}')
    return '\n'.join(out)

if __name__ == '__main__':
  hdr = ('// GENERATED by tools/theme/port_proto_css.py from the prototype stylesheet\n'
         '// (08-prototype/customer/_shared/proto.css). Do not edit; adapt in _gitpizza-app.scss.\n')
  open(sys.argv[2], 'w', encoding='utf-8').write(hdr + convert(src) + '\n')
