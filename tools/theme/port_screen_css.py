#!/usr/bin/env python3
"""Port the page-level <style> blocks of the prototype screens into
theme/web/_gitpizza-screens.scss. Rules of SCR-NN are scoped under
`.gp-app .scr-NN` (the page's root container), so screens cannot clash.

Usage: python3 tools/theme/port_screen_css.py <08-prototype/customer> <out.scss>
"""
import glob, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from port_proto_css import blocks  # noqa: E402  (reuses the brace walker)

def scoped(text, scope, indent=''):
    out = []
    for prelude, body in blocks(text):
        if prelude.startswith('@keyframes'):
            out.append(f'{indent}{prelude} {{{body}}}')
        elif prelude.startswith('@media'):
            out.append(f'{indent}{prelude} {{\n{scoped(body, scope, indent + "  ")}\n{indent}}}')
        else:
            sels = []
            for s in prelude.split(','):
                s = s.strip()
                if not s:
                    continue
                if s.startswith('body'):
                    s = s[4:].strip() or ''
                sels.append(f'{scope} {s}'.strip())
            out.append(f'{indent}{", ".join(sels)} {{{body.strip()} }}')
    return '\n'.join(out)

res = ['// GENERATED by tools/theme/port_screen_css.py from the page <style> blocks of',
       '// 08-prototype/customer/SCR-*.html. Do not edit; adapt in _gitpizza-app.scss.']
for f in sorted(glob.glob(os.path.join(sys.argv[1], 'SCR-*.html'))):
    m = re.match(r'SCR-(\d+)', os.path.basename(f))
    html = open(f, encoding='utf-8').read()
    css = '\n'.join(re.findall(r'<style>(.*?)</style>', html, re.S))
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    if css.strip():
        res.append(f'\n// ── {os.path.basename(f)}')
        res.append(scoped(css, f'.gp-app .scr-{m.group(1)}'))
open(sys.argv[2], 'w', encoding='utf-8').write('\n'.join(res) + '\n')
