#!/usr/bin/env python3
"""Generate mdlsource/90-access.mdl: grants for every guest-facing flow and page.

Guest-facing = microflows/nanoflows named ACT_* or DS_* and every page in Shop.
SUB_/SIM_/SE_/SEED_/ASU_ flows are server-side only and get no role (LITE-SEC-01).
"""
import re, subprocess

def names(kind):
    out = subprocess.run(['./mxcli', '-p', 'GitPizza.mpr', '-c', f'list {kind} in Shop'], capture_output=True, text=True).stdout
    return [m.group(1) for m in re.finditer(r'^\| (Shop\.\w+)\s', out, re.M)]

L = ['mdl 1;', '-- GENERATED by tools/gen_access.py — guest-facing flows and pages, app security.', '']
L += ["create user role Anonymous if not exists;"] if False else []
for mf in names('microflows'):
    if re.match(r'Shop\.(ACT|DS)_', mf):
        L.append(f'grant execute on microflow {mf} to Shop.Guest, Shop.Administrator;')
for nf in names('nanoflows'):
    L.append(f'grant execute on nanoflow {nf} to Shop.Guest, Shop.Administrator;')
for pg in names('pages'):
    L.append(f'grant view on page {pg} to Shop.Guest, Shop.Administrator;')
open('mdlsource/90-access.mdl', 'w').write('\n'.join(L) + '\n')
print(len(L) - 3, 'grants')
